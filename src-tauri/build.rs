fn main() -> Result<(), Box<dyn std::error::Error>> {
    const VARIABLES: &[&str] = &[
        "CVR_APP_NAME",
        "CVR_APP_BINARY",
        "CVR_APP_ID",
        "CVR_CORE_NAME",
        "CVR_CORE_ALPHA_NAME",
        "CVR_SERVICE_BINARY",
        "CVR_SERVICE_SLUG",
        "CVR_WINDOWS_SERVICE_NAME",
        "CVR_SERVICE_DISPLAY_NAME",
        "CVR_MACOS_SERVICE_ID",
        "CVR_BACKUP_DIR",
        "CVR_URL_SCHEME",
        "CVR_TUN_DEVICE",
        "CVR_TUN_DEVICE_MACOS",
        "CVR_CORE_IPC_NAME",
        "CVR_OWNER_TOKEN_FILE",
        "CVR_CORE_LOCK_NAME",
        "CVR_CUSTOM_BUILD",
    ];
    for name in VARIABLES {
        println!("cargo:rerun-if-env-changed={name}");
    }
    let value = |name, default: &str| std::env::var(name).unwrap_or_else(|_| default.to_owned());
    let app = value("CVR_APP_NAME", "Clash Verge");
    let binary = value("CVR_APP_BINARY", "clash-verge");
    let mut app_id = value("CVR_APP_ID", "io.github.clash-verge-rev.clash-verge-rev");
    let mut backup = value("CVR_BACKUP_DIR", "clash-verge-rev-backup");
    let custom = value("CVR_CUSTOM_BUILD", "0") == "1";
    let dev_service_dir = if custom {
        format!(".{binary}-dev")
    } else {
        ".clash-verge-rev-dev".to_owned()
    };
    if std::env::var_os("CARGO_FEATURE_VERGE_DEV").is_some() {
        app_id.push_str(".dev");
        backup.push_str("-dev");
    }
    for (name, value) in [
        ("CVR_COMPILED_APP_ID", app_id),
        ("CVR_COMPILED_BACKUP_DIR", backup),
        ("CVR_RUNTIME_CONFIG", format!("{binary}.yaml")),
        (
            "CVR_VERGE_CONFIG",
            if custom {
                format!("{binary}-settings.yaml")
            } else {
                "verge.yaml".to_owned()
            },
        ),
        ("CVR_CHECK_CONFIG", format!("{binary}-check.yaml")),
        ("CVR_CONFIG_HEADER", format!("# {app} Config")),
        ("CVR_RUNTIME_HEADER", format!("# {app} Runtime")),
        ("CVR_GENERATED_HEADER", format!("# Generated by {app}")),
        ("CVR_PROFILE_HEADER", format!("# Profiles Config for {app}")),
        ("CVR_DNS_HEADER", format!("# {app} DNS Config")),
        ("CVR_HEADER", format!("# {app}")),
        ("CVR_TASK_NAME_ADMIN", format!("{app} (Admin)")),
        ("CVR_TASK_XML_USER", format!("{binary}-task-user.xml")),
        ("CVR_TASK_XML_ADMIN", format!("{binary}-task-admin.xml")),
        ("CVR_DEV_SERVICE_DIR", dev_service_dir),
    ] {
        println!("cargo:rustc-env={name}={value}");
    }
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows")
        && std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc")
        && std::env::var_os("CARGO_FEATURE_CLIPPY").is_some()
    {
        // Tauri's resource is linked to the app binary, but not to Rust unit-test harnesses.
        // Give mock-context builds their own manifest so tests can resolve TaskDialogIndirect.
        let out_dir = std::env::var_os("OUT_DIR").ok_or_else(|| std::io::Error::other("OUT_DIR is not set"))?;
        let manifest_path = std::path::PathBuf::from(out_dir).join("windows-test-manifest.xml");
        std::fs::write(
            &manifest_path,
            r#"<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0">
  <dependency>
    <dependentAssembly>
      <assemblyIdentity
        type="win32"
        name="Microsoft.Windows.Common-Controls"
        version="6.0.0.0"
        processorArchitecture="*"
        publicKeyToken="6595b64144ccf1df"
        language="*"
      />
    </dependentAssembly>
  </dependency>
</assembly>
"#,
        )?;
        println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
        println!("cargo:rustc-link-arg=/MANIFESTINPUT:{}", manifest_path.display());
    }

    #[cfg(feature = "clippy")]
    {
        println!("cargo:warning=Skipping tauri_build during Clippy");
    }

    #[cfg(not(feature = "clippy"))]
    tauri_build::build();

    Ok(())
}
