pub const CUSTOM_BUILD: bool = match option_env!("CVR_CUSTOM_BUILD") {
    Some(value) => matches!(value.as_bytes(), [b'1']),
    None => false,
};

#[cfg(target_os = "macos")]
pub const DEFAULT_TUN_DEVICE: &str = TUN_DEVICE_MACOS;
#[cfg(not(target_os = "macos"))]
pub const DEFAULT_TUN_DEVICE: &str = TUN_DEVICE;

/// Persisted selectors stay compatible with existing configurations.
pub fn core_name(selector: &str) -> &'static str {
    if selector == "verge-mihomo-alpha" {
        CORE_ALPHA_NAME
    } else {
        CORE_NAME
    }
}

pub fn service_tool(action: &str) -> String {
    format!("{SERVICE_BINARY}-{action}{}", std::env::consts::EXE_SUFFIX)
}

pub fn url_schemes() -> &'static [&'static str] {
    if CUSTOM_BUILD {
        &[URL_SCHEME]
    } else {
        &["clash", URL_SCHEME]
    }
}
